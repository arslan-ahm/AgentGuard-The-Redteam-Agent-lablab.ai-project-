# One canned finding per check id, so a fake scan produces a realistic mix of severities.
_CANNED: dict[str, tuple[str, Severity, FindingCategory]] = {
    "security.headers": ("Missing security headers", Severity.MEDIUM, FindingCategory.SECURITY),
    "security.error_leak": (
        "Error response leaks internal stack trace",
        Severity.HIGH,
        FindingCategory.SECURITY,
    ),
    "qa.checkout": ("Checkout fails with HTTP 500", Severity.HIGH, FindingCategory.QA),
    "qa.console_network_errors": (
        "Console error on page load",
        Severity.LOW,
        FindingCategory.QA,
    ),
}


class FakePlanner:
    """Deterministic plan per profile (stands in for Sarah's planner)."""

    async def plan(self, target_url: str, profile: ScanProfile) -> TestPlan:
        from uuid import uuid4

        checks = _PLAN_CHECKS[profile][: MAX_TASKS_PER_PROFILE[profile]]
        tasks = [
            PlanTask(
                task_id=f"t{i}",
                check_id=check,
                description=f"Run {check}",
                params={},
                timeout_s=60,
            )
            for i, check in enumerate(checks, start=1)
        ]
        # ``scan_id`` is overwritten by the orchestrator with the real scan id.
        return TestPlan(scan_id=uuid4(), target_url=target_url, profile=profile, tasks=tasks)

    async def summarize(self, findings: list[Finding]) -> str:
        if not findings:
            return "No issues were found by the checks that ran."
        worst = min(findings, key=lambda f: list(Severity).index(f.severity))
        return (
            f"{len(findings)} finding(s). Most severe: {worst.title} "
            f"({worst.severity.value}). (Generated by the fake planner.)"
        )


class FakeSandbox:
    """Returns canned results. Mirrors the real runner's audit trail for each task."""

    def __init__(self, audit: AuditSink | None = None) -> None:
        self._audit = audit

    async def _emit(
        self,
        task: SandboxTaskInput,
        actor: AuditActor,
        action: str,
        target: str,
        ok: bool,
        why: str,
    ) -> None:
        if self._audit is None:
            return
        await self._audit.append(
            AuditEvent(
                ts=datetime.now(UTC),
                scan_id=task.scan_id,
                task_id=task.task.task_id,
                actor=actor,
                action=action,
                target=target,
                decision=AuditDecision.ALLOWED if ok else AuditDecision.BLOCKED,
                reason=why,
            )
        )

    async def run(self, task: SandboxTaskInput) -> SandboxResult:
        name = f"fake-sandbox-{task.task.task_id}"
        await self._emit(task, AuditActor.SANDBOX, "sandbox_launched", name, True, "fake")
        try:
            if task.task.params.get("containment_demo") is True:
                url = "http://169.254.169.254/latest/meta-data/"
                reason = "link-local / cloud metadata address"
                await self._emit(task, AuditActor.POLICY, "navigate", url, False, reason)
                return SandboxResult(
                    task_id=task.task.task_id,
                    status=SandboxResultStatus.BLOCKED,
                    findings=[],
                    duration_ms=5,
                    policy_events=[
                        {
                            "actor": "sandbox",
                            "action": "navigate",
                            "target": url,
                            "decision": "blocked",
                            "reason": reason,
                        }
                    ],
                )
            canned = _CANNED.get(task.task.check_id)
            findings = []
            if canned:
                title, severity, category = canned
                findings.append(
                    FindingDraft(
                        title=title,
                        category=category,
                        severity=severity,
                        confidence=0.9,
                        url=task.target_url,
                        evidence=[],
                        reproduction=[f"Open {task.target_url}", "Observe the problem"],
                        impact="Example impact (fake sandbox).",
                        recommended_fix="Example fix (fake sandbox).",
                        check_id=task.task.check_id,
                    )
                )
            return SandboxResult(
                task_id=task.task.task_id,
                status=SandboxResultStatus.FAILED if findings else SandboxResultStatus.PASSED,
                findings=findings,
                duration_ms=10,
                policy_events=[],
            )
        finally:
            await self._emit(task, AuditActor.SANDBOX, "sandbox_destroyed", name, True, "fake")
