/**
 * GitHub issue body for the approval flow (brief 6.8). Pure text generation: nothing is sent
 * from here. Filing happens only after a person approves (`POST /scans/{id}/approvals`).
 */

import type { Finding } from '../../api/contracts'
import type { ScanDetail } from '../../api/schemas'
import {
  CATEGORY_LABELS,
  checkLabel,
  DECISION_LABELS,
  decisionOf,
  formatConfidence,
  hostOf,
  PROFILE_LABELS,
  SEVERITY_LABELS,
  sortFindings,
} from '../../lib/format'

/** Keeps user/target-controlled text from breaking the Markdown table or adding mentions. */
function inline(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').replace(/@/g, '@​')
}

export function githubIssueTitle(scan: ScanDetail): string {
  const decision = decisionOf(scan.score, scan.recommendation)
  const verdict = decision ? DECISION_LABELS[decision] : 'Release audit'
  const score = scan.score === null || scan.score === undefined ? '' : ` (score ${scan.score}/100)`
  return `AgentGuard: ${verdict} for ${hostOf(scan.target_url)}${score}`
}

export function githubIssueBody(scan: ScanDetail, findings: Finding[], reportUrl?: string): string {
  const sorted = sortFindings(findings)
  const lines: string[] = [
    `**Target:** ${inline(scan.target_url)}`,
    `**Profile:** ${PROFILE_LABELS[scan.profile]}`,
    `**Score:** ${scan.score ?? 'n/a'}/100 · **Recommendation:** ${inline(scan.recommendation ?? 'not scored')}`,
    '',
  ]
  if (scan.summary) lines.push('## Summary', '', inline(scan.summary), '')

  if (sorted.length === 0) {
    lines.push('No verified findings.', '')
  } else {
    lines.push(
      '## Findings',
      '',
      '| Severity | Finding | Category | Confidence |',
      '|---|---|---|---|',
      ...sorted.map(
        (f) =>
          `| ${SEVERITY_LABELS[f.severity]} | ${inline(f.title)} | ${CATEGORY_LABELS[f.category]} | ${formatConfidence(f.confidence)} |`,
      ),
      '',
    )
    for (const f of sorted) {
      lines.push(
        `### ${SEVERITY_LABELS[f.severity]}: ${inline(f.title)}`,
        '',
        `- **URL:** ${inline(f.url)}`,
        `- **Check:** ${checkLabel(f.check_id)} (\`${inline(f.check_id)}\`)`,
        `- **Impact:** ${inline(f.impact)}`,
        '',
        '**Steps to reproduce**',
        '',
        ...f.reproduction.map((step, i) => `${i + 1}. ${inline(step)}`),
        '',
        `**Suggested fix:** ${inline(f.recommended_fix)}`,
        '',
      )
    }
  }

  lines.push(
    '---',
    reportUrl
      ? `Evidence (screenshots, network summaries) is in the [full AgentGuard report](${reportUrl}).`
      : 'Evidence (screenshots, network summaries) is in the AgentGuard report.',
    '_Generated by AgentGuard and filed only after human approval._',
  )
  return lines.join('\n')
}
